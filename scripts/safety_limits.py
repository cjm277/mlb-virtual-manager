"""Write evidence/tests/safety_limits.md: the safety limits as configured in code, and the checker's rule codes.
The report quotes these numbers, so they are read from the source here instead of being copied by hand.

Usage: python scripts/safety_limits.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend import config  # noqa: E402
from backend import main as webapp  # noqa: E402

OUT = ROOT / "evidence" / "tests" / "safety_limits.md"


def main() -> None:
    src = (ROOT / "backend" / "checker.py").read_text(encoding="utf-8")
    codes = sorted(set(re.findall(r'Issue\("[a-z_]+",\s*"([a-z_]+)"', src)) | set(re.findall(r'code="([a-z_]+)"', src)))
    limits = [
        ("Model calls per game plan", config.MAX_REQUESTS_PER_RUN),
        ("Tool calls per game plan", config.MAX_TOOL_CALLS_PER_RUN),
        ("Tokens per game plan (input + output)", f"{config.MAX_TOKENS_PER_RUN:,}"),
        ("Model steps inside one agent's loop", config.MAX_STEPS_PER_AGENT),
        ("Seconds for one agent's whole loop", config.AGENT_TIMEOUT_SECONDS),
        ("Seconds before a stalled model call is abandoned and retried", config.MODEL_REQUEST_TIMEOUT_SECONDS),
        ("Fix rounds (checker -> owner -> checker)", config.MAX_FIX_ROUNDS),
        ("Self-check retries inside a scout's or coach's loop", config.SELF_CHECK_RETRIES),
        ("Daily spending cap on plans + chat (USD)", f"{config.DAILY_BUDGET_USD:.2f}"),
        ("Hours an identical request reopens the saved plan for free", config.REUSE_HOURS),
        ("Game plans building at once (web app)", webapp.MAX_ACTIVE_RUNS),
    ]
    md = ["# Safety limits as configured in code", "",
          "Generated by `scripts/safety_limits.py` from `backend/config.py`, `backend/main.py` and `backend/checker.py`.", "",
          "| Limit | Value |", "|---|---|", *[f"| {k} | {v} |" for k, v in limits], "",
          f"**Consistency-checker rule codes: {len(codes)}** (each problem is routed to the agent that owns it):", "",
          ", ".join(f"`{c}`" for c in codes), "",
          "The stat-citation verifier and the prompt-leak guard run on top of these rules (`backend/checker.py`).", ""]
    OUT.write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
